#!/usr/bin/env node
// Requirement → test traceability (NFR-007 AC-1/AC-2, NFR-004 AC-9).
//
// Reads every docs/requirements/{REQ,NFR}-*.md, collects its acceptance criteria (**AC-n**) and
// finds tests that reference them as "REQ-002/AC-3" or "NFR-001/AC-9". Writes docs/traceability.md.
//
// Fails (exit 1) when
//   - a requirement with status "implemented" has an acceptance criterion without a test, or
//   - a test references a requirement or criterion that does not exist (typo protection).
// Criteria marked "_(manual)_" are verified by a human and listed separately.
//
// Usage: node scripts/trace.mjs [--root <repo>] [--out <file>]

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const REQUIREMENTS_DIR = 'docs/requirements';
const TEST_SOURCES = [
  { dir: 'backend/src/test', match: (f) => f.endsWith('.java') },
  { dir: 'backend/src/main/webui/src', match: (f) => f.endsWith('.spec.ts') },
  { dir: 'e2e/tests', match: (f) => f.endsWith('.ts') },
  { dir: 'scripts', match: (f) => f.endsWith('.test.mjs') },
];
const SKIP_DIRS = new Set(['node_modules', 'dist', 'target', '.angular']);
const AC_LINE = /^\s*-\s+\*\*AC-(\d+)\*\*(.*)$/;
const REFERENCE = /\b((?:REQ|NFR)-\d{3})\/AC-(\d+)\b/g;

/** Parses one requirement file into { id, title, status, milestone, criteria: [{ ac, manual }] }. */
export function parseRequirement(text) {
  const frontMatter = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  if (!frontMatter) return null;
  const fields = {};
  for (const line of frontMatter[1].split(/\r?\n/)) {
    const m = /^(\w+):\s*(.*)$/.exec(line);
    if (m) fields[m[1]] = m[2].trim();
  }
  const criteria = [];
  for (const line of text.split(/\r?\n/)) {
    const m = AC_LINE.exec(line);
    if (m) criteria.push({ ac: Number(m[1]), manual: /_\(manual\)_\s*$/.test(m[2]) });
  }
  return {
    id: fields.id,
    title: fields.title ?? '',
    status: fields.status ?? 'draft',
    milestone: fields.milestone ?? '',
    criteria,
  };
}

/** Finds all "XXX-nnn/AC-n" references in a source text, with 1-based line numbers. */
export function findReferences(text) {
  const refs = [];
  text.split(/\r?\n/).forEach((line, index) => {
    for (const m of line.matchAll(REFERENCE)) {
      refs.push({ id: m[1], ac: Number(m[2]), line: index + 1 });
    }
  });
  return refs;
}

/** Combines requirements and references into coverage rows plus a list of problems. */
export function evaluate(requirements, references) {
  const problems = [];
  const byKey = new Map();
  for (const ref of references) {
    const key = `${ref.id}/AC-${ref.ac}`;
    if (!byKey.has(key)) byKey.set(key, []);
    byKey.get(key).push(ref);
  }

  const known = new Set();
  const rows = [];
  for (const req of requirements) {
    for (const { ac, manual } of req.criteria) {
      const key = `${req.id}/AC-${ac}`;
      known.add(key);
      const tests = byKey.get(key) ?? [];
      rows.push({ req, ac, manual, tests });
      if (req.status === 'implemented' && !manual && tests.length === 0) {
        problems.push(`${key} is implemented but has no test`);
      }
    }
  }
  for (const [key, refs] of byKey) {
    if (!known.has(key)) {
      for (const ref of refs) {
        problems.push(`${ref.file}:${ref.line} references unknown criterion ${key}`);
      }
    }
  }
  return { rows, problems };
}

/** Renders the Markdown matrix. Deterministic output, so CI can check it is up to date. */
export function render(requirements, rows) {
  const out = [
    '# Traceability matrix',
    '',
    'Generated by `node scripts/trace.mjs` — do not edit by hand.',
    '',
    '## Summary',
    '',
    '| Requirement | Status | Milestone | Covered |',
    '|---|---|---|---|',
  ];
  for (const req of requirements) {
    const own = rows.filter((r) => r.req === req);
    const automated = own.filter((r) => !r.manual);
    const covered = automated.filter((r) => r.tests.length > 0).length;
    const manual = own.length - automated.length;
    const manualNote = manual > 0 ? ` (+${manual} manual)` : '';
    out.push(
      `| ${req.id} ${req.title} | ${req.status} | ${req.milestone} | ${covered}/${automated.length}${manualNote} |`,
    );
  }
  out.push('', '## Details', '', '| Criterion | Tests |', '|---|---|');
  for (const { req, ac, manual, tests } of rows) {
    const cell = manual
      ? 'manual verification'
      : tests.length === 0
        ? '—'
        : [...new Set(tests.map((t) => `\`${t.file}:${t.line}\``))].join('<br>');
    out.push(`| ${req.id}/AC-${ac} | ${cell} |`);
  }
  return out.join('\n') + '\n';
}

function listFiles(dir, match) {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return [];
  }
  return entries
    .sort()
    .flatMap((name) => {
      const path = join(dir, name);
      if (statSync(path).isDirectory()) return SKIP_DIRS.has(name) ? [] : listFiles(path, match);
      return match(name) ? [path] : [];
    });
}

function main(argv) {
  const arg = (name, fallback) => {
    const i = argv.indexOf(name);
    return i >= 0 ? argv[i + 1] : fallback;
  };
  const root = arg('--root', join(fileURLToPath(import.meta.url), '..', '..'));
  const outFile = arg('--out', join(root, 'docs/traceability.md'));

  const requirements = listFiles(join(root, REQUIREMENTS_DIR), (f) => /^(REQ|NFR)-\d{3}.*\.md$/.test(f))
    .map((file) => parseRequirement(readFileSync(file, 'utf8')))
    .filter((req) => req && req.id)
    .sort((a, b) => a.id.localeCompare(b.id));

  const references = TEST_SOURCES.flatMap(({ dir, match }) =>
    listFiles(join(root, dir), match).flatMap((file) =>
      findReferences(readFileSync(file, 'utf8')).map((ref) => ({
        ...ref,
        file: relative(root, file).split(sep).join('/'),
      })),
    ),
  );

  const { rows, problems } = evaluate(requirements, references);
  writeFileSync(outFile, render(requirements, rows));

  if (problems.length > 0) {
    console.error(`Traceability check failed:\n  - ${problems.join('\n  - ')}`);
    return 1;
  }
  console.log(`Traceability OK: ${requirements.length} requirements, ${references.length} test references.`);
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  process.exitCode = main(process.argv.slice(2));
}
